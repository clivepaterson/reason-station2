ranked AS (
    SELECT song.archive_key,
           ROW_NUMBER() OVER (
               PARTITION BY song.filename, song.filesize
               -- Keep a downloadable copy with the most complete metadata,
               -- then use the stable key to break ties reproducibly.
               ORDER BY CASE WHEN NULLIF(BTRIM(song.s3_uri), '') IS NOT NULL THEN 0 ELSE 1 END,
                        num_nonnulls(song.archive_song_id, NULLIF(song.name, ''),
                                     NULLIF(song.creator, ''), NULLIF(song.style, ''),
                                     song.date_created, song.avr,
                                     NULLIF(song.metadata_source, '')) DESC,
                        song.archive_key
           ) AS copy_number
    FROM archive_songs AS song
    JOIN verified_duplicates AS duplicate
      ON song.filename = duplicate.filename
     AND song.filesize = duplicate.filesize
)
DELETE FROM archive_songs AS song
USING ranked
WHERE song.archive_key = ranked.archive_key
  AND ranked.copy_number > 1;
